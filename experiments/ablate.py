"""Measure what the design choices change, instead of asserting it.

Runs every request in config/requests.yaml N times under each configuration, then tabulates
behaviour straight from the saved ledgers.

  uv run python experiments/ablate.py run --runs 3     # every configuration (resumable)
  uv run python experiments/ablate.py report           # rebuild experiments/results.md

Configurations (each differs from `gated` in one thing only):
  gated    the shipped engine: gated termination, opposed-incentive prompts
  naive    termination is the Critic's word plus a round cap
  generic  prompts without the role stakes and burden-of-proof clauses
"""

import argparse
import json
import statistics
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

import yaml

from deliberation.engine import deliberate
from deliberation.llm import default_provider, load_env, make_llm
from deliberation.termination import POLICIES

HERE = Path(__file__).resolve().parent
ROOT, RUNS = HERE.parent, HERE / "runs"
CONFIGS = {"gated": ("gated", ()), "naive": ("naive", ()), "generic": ("gated", (HERE / "prompts-generic",))}


def run_one(config: str, request_id: str, text: str, index: int, context: str, provider: str, model: str | None) -> str:
    folder = RUNS / config / request_id / str(index)
    if (folder / "ledger.json").exists():
        return f"skip {folder.relative_to(HERE)}"
    policy, prompts = CONFIGS[config]
    llms = {role: make_llm(provider, model) for role in ("proposer", "critic", "summarizer")}
    run = deliberate(text, context, llms, POLICIES[policy], request_id=request_id, prompt_dirs=prompts)
    run.save(folder)
    return f"done {folder.relative_to(HERE)}: {run.meta['termination']} after {run.meta['rounds']} rounds"


def metrics(folder: Path) -> dict:
    ledger = json.loads((folder / "ledger.json").read_text())
    meta = json.loads((folder / "decision.json").read_text())["meta"]
    issues = list(ledger["issues"].values())
    moves = [(e["actor"], e["move"]) for i in issues for e in i["history"]]
    proposer = [m for a, m in moves if a == "proposer"]
    rulings = [m for a, m in moves if a == "critic" and m != "RAISE"]
    return {
        "rounds": len(ledger["rounds"]), "termination": ledger["termination"], "raised": len(issues),
        "closed_over_blocking": sum(i["status"] == "UNRESOLVED" and i["severity"] in ("BLOCKER", "MAJOR") for i in issues),
        "escalated": sum(i["status"] == "ESCALATED" for i in issues),
        "defend": proposer.count("DEFEND"), "revise": proposer.count("REVISE"), "concede": proposer.count("CONCEDE"),
        "accept": rulings.count("ACCEPT"), "rulings": len(rulings),
        "rejected_concludes": sum(bool(r["feedback"]) for r in ledger["rounds"]),
        "final_disagreement": ledger["rounds"][-1]["disagreement"], "cost": meta["cost_usd"] or 0.0,
    }


def summarize(rows: list[dict]) -> dict:
    moves = sum(r["defend"] + r["revise"] + r["concede"] for r in rows) or 1
    share = lambda key: f"{100 * sum(r[key] for r in rows) / moves:.0f}%"  # noqa: E731
    rounds = [r["rounds"] for r in rows]
    return {
        "runs": str(len(rows)),
        "rounds (median, range)": f"{statistics.median(rounds):g} ({min(rounds)}–{max(rounds)})",
        "ended: consensus / converged / cap": " / ".join(str(sum(r["termination"] == t for r in rows)) for t in ("consensus", "converged", "cap")),
        "runs closed with a BLOCKER/MAJOR still open": f"{sum(r['closed_over_blocking'] > 0 for r in rows)}/{len(rows)}",
        "issues raised (mean)": f"{statistics.mean(r['raised'] for r in rows):.1f}",
        "escalated to humans (mean)": f"{statistics.mean(r['escalated'] for r in rows):.1f}",
        "Proposer moves: defend / revise / concede": f"{share('defend')} / {share('revise')} / {share('concede')}",
        "runs where the Proposer never defended": f"{sum(r['defend'] == 0 for r in rows)}/{len(rows)}",
        "Critic accept rate": f"{100 * sum(r['accept'] for r in rows) / max(1, sum(r['rulings'] for r in rows)):.0f}%",
        "CONCLUDEs rejected by the gate (total)": str(sum(r["rejected_concludes"] for r in rows)),
        "final disagreement index (mean)": f"{statistics.mean(r['final_disagreement'] for r in rows):.2f}",
        "cost per run (mean)": f"${statistics.mean(r['cost'] for r in rows):.3f}",
    }


def report() -> None:
    table = {c: summarize([metrics(f.parent) for f in sorted((RUNS / c).glob("*/*/ledger.json"))])
             for c in CONFIGS if any((RUNS / c).glob("*/*/ledger.json"))}
    if not table:
        raise SystemExit("No runs yet: uv run python experiments/ablate.py run")
    configs = list(table)
    lines = ["# Experiment results", "", "Generated by `experiments/ablate.py report` from the ledgers in `experiments/runs/`.",
             "Each configuration differs from `gated` in exactly one thing (see the module docstring).", "",
             "| Metric | " + " | ".join(configs) + " |", "|---|" + "---|" * len(configs)]
    lines += [f"| {metric} | " + " | ".join(table[c][metric] for c in configs) + " |" for metric in table[configs[0]]]
    per_request = ["", "## Per request (median rounds · runs closed with a BLOCKER/MAJOR open)", "",
                   "| Request | " + " | ".join(configs) + " |", "|---|" + "---|" * len(configs)]
    for request_id in sorted({p.name for c in configs for p in (RUNS / c).iterdir()}):
        cells = []
        for c in configs:
            rows = [metrics(f.parent) for f in sorted((RUNS / c / request_id).glob("*/ledger.json"))]
            cells.append(f"{statistics.median(r['rounds'] for r in rows):g} · {sum(r['closed_over_blocking'] > 0 for r in rows)}/{len(rows)}"
                         if rows else "—")
        per_request.append(f"| {request_id} | " + " | ".join(cells) + " |")
    (HERE / "results.md").write_text("\n".join(lines + per_request) + "\n")
    print((HERE / "results.md").read_text())


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["run", "report"])
    ap.add_argument("--runs", type=int, default=3)
    ap.add_argument("--configs", nargs="+", default=list(CONFIGS), choices=list(CONFIGS))
    ap.add_argument("--provider", choices=["anthropic", "openai"], help="default: whichever API key is set")
    ap.add_argument("--model")
    ap.add_argument("--workers", type=int, default=4)
    load_env(ROOT / ".env")
    args = ap.parse_args()
    if args.command == "report":
        return report()
    if not (provider := args.provider or default_provider()):
        raise SystemExit("No API key found: set ANTHROPIC_API_KEY or OPENAI_API_KEY (or put it in .env).")
    context = (ROOT / "config/system_context.md").read_text()
    requests = yaml.safe_load((ROOT / "config/requests.yaml").read_text())["requests"]
    jobs = [(c, r["id"], r["text"], i, context, provider, args.model)
            for c in args.configs for r in requests for i in range(1, args.runs + 1)]
    with ThreadPoolExecutor(args.workers) as pool:
        for future in as_completed([pool.submit(run_one, *job) for job in jobs]):
            try:
                print(future.result(), flush=True)
            except Exception as e:  # keep going; a failed run is simply re-attempted on the next invocation
                print(f"FAILED: {e!r}", flush=True)
    report()


if __name__ == "__main__":
    main()
